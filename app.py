# -----------------------------------------------------------------------------
# FEMA NFHL GIS QUERY ENGINE
# -----------------------------------------------------------------------------
def query_fema_nfhl(lat: float, lon: float) -> Tuple[str, str]:
    """
    Queries FEMA National Flood Hazard Layer (NFHL) ArcGIS REST API.
    Publicly accessible endpoint (Layer 28: Flood Hazard Zones).
    """
    url = "https://hazards.fema.gov/gis/nfhl/rest/services/public/NFHL/MapServer/28/query"
    params = {
        "geometry": f"{lon},{lat}",
        "geometryType": "esriGeometryPoint",
        "spatialRel": "esriSpatialRelIntersects",
        "outFields": "FLD_ZONE,ZONE_SUBTY",
        "returnGeometry": "false",
        "f": "json"
    }
    try:
        resp = requests.get(url, params=params, timeout=4)
        if resp.status_code == 200:
            data = resp.json()
            if data.get("features"):
                attr = data["features"][0].get("attributes", {})
                zone = attr.get("FLD_ZONE", "X")
                subtype = attr.get("ZONE_SUBTY", "")
                return zone, subtype
        return "X", "Standard / Area of Minimal Flood Hazard"
    except Exception:
        # Fallback offline simulation for rapid testing
        return "AE", "1% Annual Chance Flood Hazard (Simulated)"

# -----------------------------------------------------------------------------
# DETERMINISTIC UNDERWRITING RULES ENGINE
# -----------------------------------------------------------------------------
def evaluate_underwriting(zone: str, bfe: float, lag: float, claims: int) -> Dict[str, Any]:
    elev_diff = lag - bfe
    flags = []
    
    sfha_zones = ["A", "AE", "AH", "AO", "AR", "A99", "V", "VE"]
    is_sfha = any(zone.upper().startswith(z) for z in sfha_zones)
    
    if is_sfha:
        flags.append(f"Located in Special Flood Hazard Area (SFHA Zone {zone})")
        
    if elev_diff < 0:
        flags.append(f"Sub-grade exposure: Lowest Grade is {abs(elev_diff):.2f} ft below BFE")
        
    if claims >= 2:
        flags.append(f"Repetitive Loss Structure: {claims} prior claims recorded")
        
    if claims >= 2 or elev_diff < -2.0:
        tier = "Tier 3: Mandatory Senior Underwriter Review (HITL)"
        status = "REQUIRES_MANUAL_REVIEW"
        color = "red"
    elif is_sfha and elev_diff < 0:
        tier = "Tier 2: Standard Underwriter Verification"
        status = "PENDING_VERIFICATION"
        color = "orange"
    else:
        tier = "Tier 1: Accelerated Auto-Bind Eligible"
        status = "ELIGIBLE_FOR_AUTO_BIND"
        color = "green"
        
    return {
        "is_sfha": is_sfha,
        "elevation_diff": round(elev_diff, 2),
        "flags": flags,
        "tier": tier,
        "status": status,
        "color": color
    }

# -----------------------------------------------------------------------------
# LLM / AGENT MEMO SYNTHESIZER
# -----------------------------------------------------------------------------
def generate_agent_memo(app_id: str, address: str, zone: str, rules: Dict[str, Any]) -> str:
    memo = f"""### Official NFIP Underwriting Triage Memo
**Application Reference:** `{app_id}`  
**Insured Property:** {address}  
**Determined Flood Zone:** {zone} ({'Special Flood Hazard Area' if rules['is_sfha'] else 'Non-SFHA Area'})

#### Key Risk Indicators
- **Elevation Margin:** {rules['elevation_diff']} ft relative to Base Flood Elevation (BFE)
- **Identified Risk Flags:** {len(rules['flags'])} detected
"""
    for f in rules['flags']:
        memo += f"  - :warning: **{f}**\n"
    if not rules['flags']:
        memo += "  - :white_check_mark: No negative risk flags detected.\n"

    memo += f"""
#### Recommended Workflow & Routing
- **Decision:** **{rules['status']}**
- **Assigned Track:** **{rules['tier']}**

---
*FEMA AI Governance Notice (OMB M-25-21 / Responsible AI):*  
This assessment was generated by the NFIP Automation Assistant prototype. Automated binding is only authorized for Tier 1 workflows. All Tier 2 & Tier 3 determinations require explicit sign-off from a certified human underwriter.
"""
    return memo

